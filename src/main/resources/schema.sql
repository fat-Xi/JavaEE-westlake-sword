CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(40) NOT NULL UNIQUE,
 password VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'USER',
 logins INT NOT NULL DEFAULT 0, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(120) NOT NULL,
 place VARCHAR(120) NOT NULL, starts DATETIME NOT NULL, ends DATETIME NOT NULL,
 capacity INT NOT NULL, content TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
);
CREATE TABLE IF NOT EXISTS joins (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, event_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', reason VARCHAR(200) NOT NULL DEFAULT '',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_join(user_id,event_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(event_id) REFERENCES events(id)
);


CREATE TABLE IF NOT EXISTS profiles (
 user_id BIGINT PRIMARY KEY, nick VARCHAR(40) DEFAULT '', phone VARCHAR(30) DEFAULT '',
 company VARCHAR(100) DEFAULT '', tags VARCHAR(200) DEFAULT '', FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS event_info (
 event_id BIGINT PRIMARY KEY, live_url VARCHAR(500) DEFAULT '', replay_url VARCHAR(500) DEFAULT '',
 views INT DEFAULT 0, FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS join_info (
 join_id BIGINT PRIMARY KEY, channel VARCHAR(40) NOT NULL, FOREIGN KEY(join_id) REFERENCES joins(id)
);
CREATE TABLE IF NOT EXISTS subs (
 user_id BIGINT, event_id BIGINT, PRIMARY KEY(user_id,event_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS talks (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, title VARCHAR(120) NOT NULL,
 speaker VARCHAR(80) NOT NULL, room VARCHAR(80) NOT NULL, starts DATETIME NOT NULL,
 ends DATETIME NOT NULL, tags VARCHAR(200) DEFAULT '', FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS plans (
 user_id BIGINT, talk_id BIGINT, PRIMARY KEY(user_id,talk_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(talk_id) REFERENCES talks(id)
);
CREATE TABLE IF NOT EXISTS tickets (
 join_id BIGINT PRIMARY KEY, token VARCHAR(64) NOT NULL UNIQUE, checked DATETIME NULL, staff_id BIGINT NULL,
 FOREIGN KEY(join_id) REFERENCES joins(id), FOREIGN KEY(staff_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS questions (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 talk_id BIGINT NULL, featured BOOLEAN NOT NULL DEFAULT FALSE, closed BOOLEAN NOT NULL DEFAULT FALSE,
 body VARCHAR(500) NOT NULL, answer VARCHAR(1000) DEFAULT '', status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 reason VARCHAR(200) DEFAULT '', created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(event_id) REFERENCES events(id), FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT fk_questions_talk FOREIGN KEY(talk_id) REFERENCES talks(id)
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 reply_to_id BIGINT NULL,
 kind VARCHAR(20) NOT NULL, title VARCHAR(120) NOT NULL, body TEXT NOT NULL,
 url VARCHAR(500) DEFAULT '', image VARCHAR(500) DEFAULT '', product VARCHAR(200) DEFAULT '',
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', reason VARCHAR(200) DEFAULT '',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(event_id) REFERENCES events(id), FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT fk_posts_reply FOREIGN KEY(reply_to_id) REFERENCES posts(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS comment_reports (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 post_id BIGINT NOT NULL, reporter_id BIGINT NOT NULL, reason VARCHAR(200) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', resolution VARCHAR(200) NOT NULL DEFAULT '',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP, reviewed_at TIMESTAMP NULL DEFAULT NULL,
 UNIQUE KEY uq_comment_report (post_id,reporter_id),
 FOREIGN KEY(post_id) REFERENCES posts(id), FOREIGN KEY(reporter_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS likes (
 user_id BIGINT, post_id BIGINT, PRIMARY KEY(user_id,post_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(post_id) REFERENCES posts(id)
);
CREATE TABLE IF NOT EXISTS comment_dislikes (
 user_id BIGINT, post_id BIGINT, PRIMARY KEY(user_id,post_id),
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS votes (
 user_id BIGINT, question_id BIGINT, PRIMARY KEY(user_id,question_id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(question_id) REFERENCES questions(id)
);
CREATE TABLE IF NOT EXISTS question_dislikes (
 user_id BIGINT, question_id BIGINT, PRIMARY KEY(user_id,question_id),
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS files (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 name VARCHAR(200) NOT NULL, path VARCHAR(100) NOT NULL, size BIGINT NOT NULL,
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(event_id) REFERENCES events(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS notes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, body VARCHAR(500) NOT NULL,
 seen BOOLEAN DEFAULT FALSE, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS perms (role VARCHAR(20), code VARCHAR(30), PRIMARY KEY(role,code));
CREATE TABLE IF NOT EXISTS logs (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, action VARCHAR(100) NOT NULL,
 detail VARCHAR(500) DEFAULT '', created TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS app_meta (name VARCHAR(40) PRIMARY KEY);


-- 展商办会申请独立于正式活动；管理员审核不自动发布。
CREATE TABLE IF NOT EXISTS requests (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL,
 title VARCHAR(120) NOT NULL, place VARCHAR(120) NOT NULL,
 starts DATETIME NOT NULL, ends DATETIME NOT NULL, capacity INT NOT NULL,
 contact VARCHAR(100) NOT NULL, content TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT', reason VARCHAR(200) DEFAULT '',
 event_id BIGINT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS request_files (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, request_id BIGINT NOT NULL,
 name VARCHAR(180) NOT NULL, path VARCHAR(100) NOT NULL, size BIGINT NOT NULL,
 FOREIGN KEY(request_id) REFERENCES requests(id)
);

CREATE TABLE IF NOT EXISTS request_history (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, request_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 action VARCHAR(300) NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(request_id) REFERENCES requests(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, talk_id BIGINT NOT NULL UNIQUE,
 starts DATETIME NOT NULL, ends DATETIME NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 code VARCHAR(64) NOT NULL UNIQUE, FOREIGN KEY(talk_id) REFERENCES talks(id)
);
CREATE TABLE IF NOT EXISTS marks (
 session_id BIGINT NOT NULL, user_id BIGINT NOT NULL, staff_id BIGINT NOT NULL,
 checked DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(session_id,user_id),
 FOREIGN KEY(session_id) REFERENCES attendance(id), FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(staff_id) REFERENCES users(id)
);

-- 管理员发起投票；每名参会者在同一投票中只保留一票。
CREATE TABLE IF NOT EXISTS polls (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, title VARCHAR(120) NOT NULL,
 starts DATETIME NOT NULL, ends DATETIME NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS poll_options (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, poll_id BIGINT NOT NULL, label VARCHAR(120) NOT NULL,
 UNIQUE KEY option_poll(id,poll_id), FOREIGN KEY(poll_id) REFERENCES polls(id)
);
CREATE TABLE IF NOT EXISTS ballots (
 poll_id BIGINT NOT NULL, user_id BIGINT NOT NULL, option_id BIGINT NOT NULL,
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(poll_id,user_id),
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(option_id,poll_id) REFERENCES poll_options(id,poll_id)
);

CREATE TABLE IF NOT EXISTS replays (
 talk_id BIGINT PRIMARY KEY, name VARCHAR(180) NOT NULL, type VARCHAR(30) NOT NULL,
 data LONGBLOB NOT NULL, FOREIGN KEY(talk_id) REFERENCES talks(id)
);

-- 展商送审版本与正式会议分开保存；撤销保留审计记录，不创建草稿。
CREATE TABLE IF NOT EXISTS exhibit_meetings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL,
 event_id BIGINT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 payload LONGTEXT NOT NULL, reason VARCHAR(200) DEFAULT '',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(event_id) REFERENCES events(id)
);
CREATE TABLE IF NOT EXISTS exhibit_reviews (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, meeting_id BIGINT NOT NULL,
 kind VARCHAR(20) NOT NULL, payload LONGTEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', reason VARCHAR(200) DEFAULT '',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(meeting_id) REFERENCES exhibit_meetings(id)
);

CREATE TABLE IF NOT EXISTS site_views(day DATE PRIMARY KEY, views BIGINT NOT NULL DEFAULT 0);
